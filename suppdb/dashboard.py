"""Builds output/index.html: a single self-contained static dashboard from output/results.json.

No server needed: data is embedded as JSON and charts are drawn as inline SVG by a little vanilla
JavaScript; PNG forest/funnel plots in output/figures/ are linked. Plain-language takeaways are
generated by fixed rules from the pooled numbers (direction, CI vs. no effect, size, I2, k, Egger).
"""
import datetime as dt, html, json, os, sys
from common import OUTPUT_DIR, DB_PATH, connect, load_settings

RATIO = {"RR", "OR", "HR"}

def size_word(meas, v):
    if meas == "SMD":
        a = abs(v)
        return "trivial" if a < 0.2 else "small" if a < 0.5 else "moderate" if a < 0.8 else "large"
    return None

def fmt(v, meas):
    if v is None: return ""
    if meas in RATIO: return f"{v:.2f}"
    return f"{v:.1f}" if abs(v) >= 10 else f"{v:.2f}"

def takeaway(label, level, r):
    k = r.get("k", 0)
    if "pooled" not in r:
        return f"Not enough extracted effect sizes to pool (k={k})."
    meas, p, lo, hi = r["measure"], r["pooled"], r["ci_low"], r["ci_high"]
    null = 1 if meas in RATIO else 0
    excludes = hi < null or lo > null
    lower = p < null
    o = label[0].lower() + label[1:]
    if meas in RATIO:
        pct = abs(1 - p) * 100
        eff = f"{pct:.0f}% {'lower' if lower else 'higher'} risk of {o}"
    elif meas == "MD":
        eff = f"{'lower' if lower else 'higher'} {o} by {abs(p):.1f}{(' ' + r['unit']) if r.get('unit') else ''}"
    else:
        eff = f"{size_word(meas, p)} {'decrease' if lower else 'increase'} in {o} (SMD {p:.2f})"
    s = ("Points to " if excludes else "No clear effect: the estimate suggests ") + eff
    s += "; the 95% CI excludes no effect." if excludes else ", but the 95% CI includes no effect."
    notes = []
    if k < 4: notes.append(f"only {k} estimates")
    i2 = r.get("I2") or 0
    if i2 >= 75: notes.append(f"results are very inconsistent (I² {i2:.0f}%)")
    elif i2 >= 50: notes.append(f"results are moderately inconsistent (I² {i2:.0f}%)")
    eg = (r.get("egger") or {}).get("p")
    if eg is not None and eg < 0.10: notes.append(f"funnel asymmetry suggests small-study or publication bias (Egger p={eg:.3f})")
    if level == "pooled": notes.append("summary of overlapping published meta-analyses")
    if notes: s += " Caveats: " + "; ".join(notes) + "."
    return s

def main():
    with open(os.path.join(OUTPUT_DIR, "results.json"), encoding="utf-8") as f:
        R = json.load(f)
    con = connect()
    runs = [dict(zip(["started_at", "finished_at", "new_records", "new_effects", "notes"], r)) for r in
            con.execute("SELECT started_at, finished_at, new_records, new_effects, notes FROM runs WHERE step='cycle' ORDER BY id DESC LIMIT 15")]
    con.close()
    sups = []
    for s in R["supplements"]:
        rows = []
        for o in s["outcomes"]:
            for lev, r in o["levels"].items():
                rows.append(dict(o=o["label"], ok=o["key"], lev=lev, m=r["measure"], u=r.get("unit"), k=r["k"], N=r.get("total_n"),
                                 p=r.get("pooled"), lo=r.get("ci_low"), hi=r.get("ci_high"), I2=r.get("I2"), eg=(r.get("egger") or {}).get("p"),
                                 sig=[r.get("n_sig_below_null"), r.get("n_ns"), r.get("n_sig_above_null")],
                                 forest=r.get("forest_png"), funnel=r.get("funnel_png"), take=takeaway(o["label"], lev, r),
                                 f=[[e["pmid"], e["year"], e["value"], e["ci_low"], e["ci_high"], (e.get("title") or "")[:140]] for e in r["effects"]]))
        used = {e[0] for row in rows for e in row["f"]}
        mas = [dict(pmid=m["pmid"], year=m["year"], title=m["title"], journal=m["journal"], conclusion=m.get("conclusion", ""),
                    used=m["pmid"] in used) for m in s.get("meta_analyses", [])]
        mas.sort(key=lambda m: (not m["used"], -(m["year"] or 0)))
        sups.append(dict(key=s["key"], label=s["label"], n=s["n_articles"], d=s["by_design"], yb=s["by_year"], e=s["n_effects"],
                         lev=s.get("effects_by_level", {}), src=s.get("effects_by_source", {}), ft=s.get("fulltext_pending"), rows=rows, mas=mas[:25],
                         n_mas=len(mas)))
    data = dict(generated=R["generated_at"], stats={k: R["stats"][k] for k in ("total_articles", "total_effects", "by_design", "by_year")},
                coverage=R.get("coverage", {}), sups=sups, runs=runs, db=os.path.basename(DB_PATH))
    page = TEMPLATE.replace("/*DATA*/null", json.dumps(data, default=float, ensure_ascii=False).replace("</", "<\\/"))
    tmp = os.path.join(OUTPUT_DIR, "index.html.tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(page)
    for i in range(10):  # Windows: the target can be briefly locked (antivirus, indexer)
        try:
            os.replace(tmp, os.path.join(OUTPUT_DIR, "index.html")); break
        except PermissionError:
            if i == 9: raise
            import time; time.sleep(1)
    print(f"dashboard written: {os.path.join(OUTPUT_DIR, 'index.html')} ({len(page)//1024} KB, {len(sups)} supplements)")

